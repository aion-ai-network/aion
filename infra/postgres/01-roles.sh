#!/bin/sh
set -eu

psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  --set=ON_ERROR_STOP=1 \
  --set=runtime_password="$AION_DB_PASSWORD" \
  --set=migration_password="$AION_DB_MIGRATION_PASSWORD" <<'SQL'
CREATE ROLE aion_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS
  PASSWORD :'migration_password';
CREATE ROLE aion_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS
  PASSWORD :'runtime_password';
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO aion_migrator;
CREATE SCHEMA app AUTHORIZATION aion_migrator;
GRANT USAGE ON SCHEMA app TO aion_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE aion_migrator IN SCHEMA app
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO aion_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE aion_migrator IN SCHEMA app
  GRANT USAGE, SELECT ON SEQUENCES TO aion_runtime;
SQL
